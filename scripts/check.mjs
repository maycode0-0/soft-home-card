import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import {fileURLToPath} from 'node:url';
import {DEVICES} from '../src/model.js';
const root=path.resolve(fileURLToPath(new URL('..',import.meta.url)));
const read=name=>fs.readFileSync(path.join(root,name),'utf8');
const pkg=JSON.parse(read('package.json'));
const lock=JSON.parse(read('package-lock.json'));
const hacs=JSON.parse(read('hacs.json'));
assert.ok(hacs.name,'HACS display name required');
assert.equal(hacs.filename,pkg.name+'.js');
assert.equal(lock.version,pkg.version);
assert.equal(lock.packages[''].version,pkg.version);
assert.ok(/^\d+\.\d+\.\d+$/.test(pkg.version),'Stable semantic version required');
assert.ok(read('CHANGELOG.md').includes('## '+pkg.version),'Changelog entry required');
assert.equal(Object.keys(DEVICES).length,23);
assert.equal(fs.readdirSync(path.join(root,'assets/devices')).filter(x=>x.endsWith('.svg')).length,Object.keys(DEVICES).length);
const bundle=read('dist/'+hacs.filename);
assert.ok(bundle.startsWith('/* Soft Home Card v'+pkg.version+' |'));
assert.ok(!/D:\\own|C:\\Users|D:\/own|C:\/Users/.test(bundle),'No local paths in bundle');
new vm.Script(bundle,{filename:hacs.filename});
const index=process.argv.indexOf('--tag');
if(index>=0)assert.equal(process.argv[index+1],'v'+pkg.version,'Git tag must match package.json');
console.log('HACS manifest, version, assets, lockfile and bundle syntax verified.');
